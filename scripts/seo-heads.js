#!/usr/bin/env node
/**
 * Writes the SEO tags into the <head> of every English page (run after editing i18n/seo.json):
 *
 *   npm run seo
 *
 * Per page: <title>, meta description, robots, canonical, Open Graph, Twitter card and JSON-LD,
 * between <!-- SEO:start --> and <!-- SEO:end --> (re-running replaces the block, so it is safe
 * to run any number of times). Titles and descriptions come from i18n/seo.json; blog posts use
 * their own title and first paragraph. The Arabic pages get the same tags, translated and pointed
 * at /ar/, from scripts/build-ar.js.
 *
 * Pages listed in seo.json "_noindex" (template demo pages, 404) only get robots noindex.
 * Pages in "_dynamic" (project.html?id=…, case-study.html?slug=…) get no canonical/og:url here:
 * shared.js sets those, with the query string, once the CMS content has loaded.
 */
const fs = require('fs');
const path = require('path');
const cheerio = require('cheerio');

const ROOT = path.join(__dirname, '..');
const SEO = JSON.parse(fs.readFileSync(path.join(ROOT, 'i18n', 'seo.json'), 'utf8'));
const SITE = SEO._site;
const BRAND = 'SCALEN';
const OG_IMAGE = SITE + '/assets/img/brand/og-en.jpg';
const LOGO = SITE + '/assets/img/brand/apple-touch-icon.png';

const esc = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const norm = s => s.replace(/\s+/g, ' ').trim();
const pageUrl = f => SITE + (f === 'index.html' ? '/' : '/' + f);

// ~155 characters: whole sentences if they fit, else cut at a word boundary
function clip(text, max = 165) {
  text = norm(text);
  if (text.length <= max) return text;
  const sentences = text.match(/[^.!?]+[.!?]+(\s|$)/g) || [];
  let out = '';
  for (const s of sentences) { if ((out + s).trim().length > max) break; out += s; }
  if (out.trim().length >= 90) return out.trim();
  return text.slice(0, 157).replace(/\s+\S*$/, '').replace(/[,;:—–-]$/, '') + '…';
}

function isoDate(s) {
  const d = new Date(s + ' 12:00 UTC');
  return isNaN(d) ? null : d.toISOString().slice(0, 10);
}

function titleFor(file, oldTitle) {
  if (SEO.pages[file] && SEO.pages[file].title) return SEO.pages[file].title;
  // "Post title — Scalen" → "Post title | SCALEN"
  return norm(oldTitle).replace(/(\s+[—|]\s+Scalen\.?)+$/i, '') + ' | ' + BRAND;
}

function block(lines) {
  return '<!-- SEO:start — generated by scripts/seo-heads.js from i18n/seo.json; edit there and run `npm run seo` -->\n  '
    + lines.join('\n  ') + '\n  <!-- SEO:end -->';
}

const pages = fs.readdirSync(ROOT).filter(f => f.endsWith('.html')).sort();
const report = [];

for (const file of pages) {
  const src = path.join(ROOT, file);
  let html = fs.readFileSync(src, 'utf8');
  const $ = cheerio.load(html);

  const oldTitle = $('title').first().text();
  const title = titleFor(file, oldTitle);
  const noindex = SEO._noindex.includes(file);
  const dynamic = SEO._dynamic.includes(file);
  const isPost = $('.post-body').length > 0;

  let description = SEO.pages[file] && SEO.pages[file].description;
  if (!description && isPost) description = clip($('.post-body p').first().text());

  const lines = [];
  if (noindex) {
    lines.push('<meta name="robots" content="noindex, follow" />');
    if (description) lines.push(`<meta name="description" content="${esc(description)}" />`);
  } else {
    if (!description) throw new Error(`${file}: no description — add it to i18n/seo.json`);
    const url = pageUrl(file);
    lines.push(`<meta name="description" content="${esc(description)}" />`);
    lines.push('<meta name="robots" content="index, follow, max-image-preview:large" />');
    if (!dynamic) lines.push(`<link rel="canonical" href="${url}" />`);
    lines.push(`<meta property="og:type" content="${isPost ? 'article' : 'website'}" />`);
    lines.push(`<meta property="og:site_name" content="${BRAND}" />`);
    lines.push(`<meta property="og:title" content="${esc(title)}" />`);
    lines.push(`<meta property="og:description" content="${esc(description)}" />`);
    if (!dynamic) lines.push(`<meta property="og:url" content="${url}" />`);
    lines.push(`<meta property="og:image" content="${OG_IMAGE}" />`);
    lines.push('<meta property="og:image:width" content="1200" />');
    lines.push('<meta property="og:image:height" content="630" />');
    lines.push(`<meta property="og:image:alt" content="${esc(BRAND + ' — Performance marketing & lead generation')}" />`);
    lines.push('<meta property="og:locale" content="en_US" />');
    lines.push('<meta property="og:locale:alternate" content="ar_AR" />');
    lines.push('<meta name="twitter:card" content="summary_large_image" />');
    lines.push(`<meta name="twitter:title" content="${esc(title)}" />`);
    lines.push(`<meta name="twitter:description" content="${esc(description)}" />`);
    lines.push(`<meta name="twitter:image" content="${OG_IMAGE}" />`);

    let ld = null;
    if (file === 'index.html') {
      ld = {
        '@context': 'https://schema.org',
        '@graph': [
          {
            '@type': 'ProfessionalService',
            '@id': SITE + '/#organization',
            name: BRAND,
            alternateName: 'SCALEN Marketing',
            url: SITE + '/',
            logo: LOGO,
            image: OG_IMAGE,
            description: SEO.org_description,
            email: 'hello@scalen.marketing',
            address: { '@type': 'PostalAddress', addressLocality: 'Istanbul', addressCountry: 'TR' },
            areaServed: ['TR', 'Middle East', 'Europe'],
            knowsAbout: ['Performance marketing', 'Lead generation', 'Google Ads', 'Meta Ads', 'TikTok Ads', 'Conversion tracking', 'Marketing automation'],
          },
          {
            '@type': 'WebSite',
            '@id': SITE + '/#website',
            name: BRAND,
            url: SITE + '/',
            inLanguage: ['en', 'ar'],
            publisher: { '@id': SITE + '/#organization' },
          },
        ],
      };
    } else if (isPost) {
      const headline = norm($('.post-title').first().text() || $('h1').first().text());
      const date = isoDate(norm($('.post-date').first().text()));
      ld = {
        '@context': 'https://schema.org',
        '@type': 'BlogPosting',
        headline,
        description,
        image: OG_IMAGE,
        ...(date ? { datePublished: date, dateModified: date } : {}),
        inLanguage: 'en',
        url: pageUrl(file),
        mainEntityOfPage: pageUrl(file),
        author: { '@type': 'Organization', name: BRAND, url: SITE + '/' },
        publisher: { '@type': 'Organization', '@id': SITE + '/#organization', name: BRAND, logo: { '@type': 'ImageObject', url: LOGO } },
      };
    }
    if (ld) lines.push(`<script type="application/ld+json">${JSON.stringify(ld)}</script>`);
  }

  // Title: new text, no data-brand (the CMS no longer rewrites SEO titles)
  html = html.replace(/<title[^>]*>[\s\S]*?<\/title>/, `<title>${esc(title)}</title>`);
  // Replace the previous block, or insert it after the hreflang links (else after <title>)
  const re = /<!-- SEO:start[\s\S]*?<!-- SEO:end -->/;
  if (re.test(html)) html = html.replace(re, block(lines));
  else {
    const anchor = html.match(/<link rel="alternate" hreflang="x-default"[^>]*>/) || html.match(/<\/title>(<!--[^>]*-->)?/);
    html = html.replace(anchor[0], anchor[0] + '\n  ' + block(lines));
  }
  fs.writeFileSync(src, html);
  report.push(`${noindex ? 'noindex ' : 'index   '} ${file.padEnd(28)} ${title}  [${description ? description.length : 0}]`);
}
console.log(report.join('\n'));
